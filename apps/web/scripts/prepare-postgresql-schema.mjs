import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(scriptDirectory, "..");
const sourcePath = resolve(webRoot, "prisma/schema.prisma");
const targetPath = resolve(webRoot, "prisma/postgresql/schema.prisma");
const sqliteProvider = 'provider = "sqlite"';

export function normalizeLineEndings(content) {
  return content.replace(/\r\n?/g, "\n");
}

export function hasEquivalentSchemaContent(current, generated) {
  return normalizeLineEndings(current) === normalizeLineEndings(generated);
}

async function main() {
  const checkOnly = process.argv.includes("--check");
  const source = await readFile(sourcePath, "utf8");

  if (!source.includes(sqliteProvider)) {
    throw new Error(`Expected the canonical Prisma schema to contain ${sqliteProvider}.`);
  }

  const generated = [
    "// Generated by scripts/prepare-postgresql-schema.mjs. Do not edit directly.",
    source.replace(sqliteProvider, 'provider = "postgresql"').trimStart(),
  ].join("\n");

  if (checkOnly) {
    const current = await readFile(targetPath, "utf8").catch(() => "");
    if (!hasEquivalentSchemaContent(current, generated)) {
      process.stderr.write(
        "The PostgreSQL Prisma schema is stale. Run pnpm --filter @battleness/web prisma:postgres:prepare.\n",
      );
      process.exitCode = 1;
    }
  } else {
    await mkdir(dirname(targetPath), { recursive: true });
    await writeFile(targetPath, generated, "utf8");
    process.stdout.write(`Generated ${targetPath}.\n`);
  }
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) await main();
